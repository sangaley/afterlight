#!/usr/bin/env python3
"""Put the reworked fleet into the game.

The user's call (2026-11-23, "whole reworked fleet"): the 192 ships approved
on the review site replace the old faction ships everywhere -- spawns,
patrols, moored and visiting ships, starport hubs, faction stations.

- Copies each kept design from designs/rework/<slug>/<key>.json to
  designs/factions/<slug>/<key>.json, compact. The paint is left out: an AI
  ship wears its faction's livery at spawn (ai_ship::livery,
  vfx::ship_roof::ship_paint_for), the same scheme the portraits were painted
  in, and the per-cell paint was half of every file.
- Removes the old class designs that are no longer on any roster (they stay
  in git history). designs/factions/<slug>.json, each faction's original
  single design, stays: it is the fallback a save's unknown class flies.
- Writes the rosters (src/ai_ship/roster_classes.rs) from each ship's class
  label on the site: scouts, line ships, capitals, bosses, experimentals,
  traders. Stations and defence platforms go to diplomacy/stations.rs, not
  the rosters.

    python3 tools/fleet-rework/integrate.py
"""
import importlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CONCEPT_DIR = os.path.join(ROOT, "tools", "fleet-concepts")
REWORK = os.path.join(ROOT, "designs", "rework")
FACTIONS = os.path.join(ROOT, "designs", "factions")
sys.path.insert(0, CONCEPT_DIR)

ENUM = {
    "terran_hegemony": "TerranHegemony", "eternal_hegemony": "EternalHegemony",
    "gilded_throne": "GildedThrone", "broken_choir": "BrokenChoir",
    "synthesis_collective": "SynthesisCollective", "corpse_stars": "CorpseStars",
    "stellar_preserve": "StellarPreserve", "the_silence": "TheSilence",
    "shepherd": "Shepherd", "recursive_kingdom": "RecursiveKingdom",
    "merchant_princes": "MerchantPrinces", "free_haulers_compact": "FreeHaulersCompact",
}

# Each role's share of a faction's new ships, split among its classes:
# scouts and line ships are the bulk of any system, traders common enough to
# notice, experimentals and capitals things you remember meeting.
ROLE_WEIGHT = {"Scout": 120, "Line": 180, "Civilian": 60, "Experimental": 32, "Capital": 24, "Boss": 12}

# Display names the rosters can't share across factions.
RENAME = {("recursive_kingdom", "ram"): "Kingdom Ram"}


def role_of(cls):
    c = cls.lower()
    if "station" in c or "platform" in c:
        return None
    if c.startswith("boss"):
        return "Boss"
    if c.startswith("experimental"):
        return "Experimental"
    if c.startswith(("trade", "civilian", "industrial")):
        return "Civilian"
    if c.startswith(("scout", "picket")):
        return "Scout"
    if c.startswith(("flagship", "battleship", "battlecruiser", "carrier", "capital", "dreadnought")):
        return "Capital"
    return "Line"


def kept_ships():
    src = open(os.path.join(HERE, "site.py")).read()
    start = src.index("MODULES = {")
    ns = {}
    exec(src[start:src.index("\n}\n", start) + 2], ns)
    cuts = json.load(open(os.path.join(HERE, "cuts.json")))
    out = {}
    for slug, mods in ns["MODULES"].items():
        for m in mods:
            if not os.path.exists(os.path.join(CONCEPT_DIR, m + ".py")):
                continue
            for key, _fn, name, cls, _note in importlib.import_module(m).CONCEPTS:
                if key in cuts.get(slug, {}).get("cut", {}):
                    continue
                if not os.path.exists(os.path.join(REWORK, slug, f"{key}.json")):
                    raise SystemExit(f"{slug}/{key} is on the roster but was never refit")
                out.setdefault(slug, []).append((key, RENAME.get((slug, key), name), cls))
    return out


def compact(design):
    design.pop("paint", None)
    for m in design["modules"]:
        for k in ("custom_name", "subcomponents", "extras"):
            if m.get(k) is None:
                m.pop(k, None)
    return json.dumps(design, separators=(",", ":"))


def main():
    ships = kept_ships()
    total = 0
    for slug, rows in ships.items():
        d = os.path.join(FACTIONS, slug)
        os.makedirs(d, exist_ok=True)
        keep = {f"{k}.json" for k, _, _ in rows}
        for f in os.listdir(d):
            if f.endswith(".json") and f not in keep:
                os.remove(os.path.join(d, f))
        for key, _, _ in rows:
            text = compact(json.load(open(os.path.join(REWORK, slug, f"{key}.json"))))
            open(os.path.join(d, f"{key}.json"), "w").write(text)
            total += len(text)

    lines = [
        "// Generated by tools/fleet-rework/integrate.py from the review site's",
        "// approved fleet (2026-11-23). Edit the script, not this file.",
        "",
        "use super::roster::{class, ClassRole::*, ShipClass};",
        "",
    ]
    stations = []
    for slug, rows in ships.items():
        by_role = {}
        for key, name, cls in rows:
            r = role_of(cls)
            if r is None:
                stations.append((slug, key, name, cls))
                continue
            by_role.setdefault(r, []).append((key, name))
        lines.append(f"pub const {slug.upper()}: &[ShipClass] = &[")
        for role in ("Scout", "Line", "Capital", "Boss", "Experimental", "Civilian"):
            members = by_role.get(role, [])
            for key, name in members:
                w = max(1, round(ROLE_WEIGHT[role] / len(members)))
                lines.append(f'    class("{key}", "{name}", {role}, {w}),')
        lines.append("];")
        lines.append("")
    open(os.path.join(ROOT, "src", "ai_ship", "roster_classes.rs"), "w").write("\n".join(lines))
    print(f"{sum(len(r) for r in ships.values())} ships, {total / 1e6:.1f} MB of designs")
    for s in stations:
        print("station:", *s)


if __name__ == "__main__":
    main()
